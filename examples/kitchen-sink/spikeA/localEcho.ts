/**
 * The error a refused write is answered with.
 *
 * Shaped like a `@sanity/client` `ClientError` (`statusCode` on the error
 * object) so Studio's own error handling reads it the way it reads a real one.
 */
function writeRefusal(refusal: {status?: number; message: string}): Error {
  const error = new Error(`[spike-a] write not acknowledged — ${refusal.message}`)
  if (refusal.status !== undefined) {
    ;(error as unknown as Rec).statusCode = refusal.status
  }
  return error
}

/**
 * Return a blocked write's synthetic success in the shape the caller expects.
 * `onDelivered` fires at most once even if Studio subscribes to the observable
 * more than once — a second echo would carry the same transactionId and break
 * the previousRev chain (dedupeListenerEvents would drop it, but do not rely
 * on that).
 *
 * `persist` (when persistence is on) is awaited BEFORE the success is handed
 * back, so the order Studio observes is: on disk, then "saved", then the
 * listener frame. Its promise is memoized for the same reason `once` exists —
 * a second subscribe must not become a second POST.
 *
 * AND THEN THE PROTOCOL GETS A VETO. `acknowledgeWrite()` is consulted after the
 * persistence attempt, and when it says no — a 401/403 seen anywhere in this
 * session, or a logout — the caller gets an *error* instead of a synthetic
 * success, and `onDelivered` never runs, so no listener frame is emitted and the
 * revision chain does not advance. A write that cannot be persisted must not
 * look saved; a pane showing content that exists nowhere is worse than a visible
 * failure. Note the asymmetry with a 5xx/offline overlay, which still gets the
 * synthetic success: that degradation is what `SPIKE_OVERLAY_PERSIST` was
 * designed to survive, and it is transient. An expired token is not.
 *
 * The veto is consulted BEFORE the persistence attempt as well as after. An
 * already-dead session must not POST a write it has decided to disown, or the
 * edit lands on disk and is reported failed — the mirror image of the bug.
 */
function blockedResult(
  kind: Kind,
  value: Rec,
  onDelivered: () => void,
  persist?: () => Promise<void>,
  blockedEntry?: EchoBlockedEntry | null,
): unknown {
  let fired = false
  const once = (): void => {
    if (fired) return
    fired = true
    onDelivered()
  }

  /** null when the write may be acknowledged, otherwise the error to raise. */
  const refusal = (): Error | null => {
    const ack = protocol.acknowledgeWrite()
    if (ack.ok) return null
    if (blockedEntry) blockedEntry.handled = false
    const error = writeRefusal(ack.error ?? {message: 'the session cannot accept writes'})
    noteError(error.message)
    console.error(error.message)
    return error
  }

  let pending: Promise<void> | null = null
  /* The flag check belongs HERE, not only inside `persistPlan`: with persistence
   * off the result must stay synchronous. Routing through an already-resolved
   * promise would still defer the observable's `next` by a microtask, and "the
   * flag is off" has to mean *nothing* changed.
   *
   * `persistPlan` reports its own failures and always resolves, so this can
   * never reject and never blocks the editor on a downed server. */
  const ready =
    persist === undefined || !isPersistEnabled()
      ? null
      : (): Promise<void> => (pending ??= persist())

  if (kind === 'observable') {
    if (ready === null) {
      const refused = refusal()
      if (refused) return observableThrowing<Rec>(refused)
      return observableOf(value, once)
    }
    return makeObservable<Rec>((subscriber) => {
      const refusedUpFront = refusal()
      if (refusedUpFront) {
        subscriber.error(refusedUpFront)
        return
      }
      let cancelled = false
      void ready().then(() => {
        if (cancelled) return
        const refused = refusal()
        if (refused) {
          subscriber.error(refused)
          return
        }
        subscriber.next(value)
        subscriber.complete()
        once()
      })
      return () => {
        cancelled = true
      }
    })
  }

  if (ready === null) {
    const refused = refusal()
    if (refused) return Promise.reject(refused)
    once()
    return Promise.resolve(value)
  }
  const refusedUpFront = refusal()
  if (refusedUpFront) return Promise.reject(refusedUpFront)
  return ready().then(() => {
    const refused = refusal()
    if (refused) throw refused
    once()
    return value
  })
}

/**
 * Record a 401/403 hiding in whatever the transport threw.
 *
 * Only called from the session's own plumbing — the pair listener, its snapshot
 * fetch, and the `/commit` POST. A 403 from an arbitrary query could be a
 * dataset ACL rather than a dead token, and over-reporting stops every
 * subsequent write.
 */
function noteAuthFailureFrom(error: unknown, source: 'listener' | 'read' | 'write'): void {
  const status = authStatusOf(error)
  if (status === undefined) return
  protocol.noteAuthFailure({
    status,
    source,
    message: error instanceof Error ? error.message : String(error),
  })
  syncSessionLog()
}

/**
 * Pass a read through untouched, learning `_rev` from whatever it returns.
 *
 * SCOPE, since the read layer landed: this is the **passthrough** tap only — the
 * `fetch` queries the overlay cannot answer exactly, and every `fetch` when
 * persistence is off. `getDocument` / `getDocuments` go through
 * {@link overlayVersionRead} instead, which does the same seeding and replay and
 * then resolves the answer.
 *
 * `keepDocuments` marks a read whose result is *authoritative* about the
 * revision chain, and whose failures are the session's own (so a 401 there ends
 * the session — a 403 on an arbitrary query may just be a dataset ACL).
 * `requestedIds` are the ids the caller ASKED for, which is not the same as the
 * ids that came back: a draft the Content Lake has never seen returns `null`,
 * and those are precisely the ones the overlay has to replay.
 */
function tapRead(result: unknown, keepDocuments: boolean, requestedIds: string[] = []): unknown {
  if (!result) return result
  const observed = (value: unknown): void => {
    try {
      seedFromResult(value, keepDocuments)
    } catch (err) {
      noteError(`rev seed failed: ${String(err)}`)
    }
    if (keepDocuments) scheduleHydrationReplay(requestedIds)
  }
  if (isRec(result) && typeof (result as Rec).subscribe === 'function') {
    captureObservableCtor(result)
    const source = result as unknown as MinimalObservable<unknown>
    return makeObservable<unknown>((subscriber) =>
      source.subscribe({
        next: (value) => {
          observed(value)
          subscriber.next(value)
        },
        error: (err) => {
          if (keepDocuments) noteAuthFailureFrom(err, 'read')
          subscriber.error(err)
        },
        complete: () => subscriber.complete(),
      }),
    )
  }
  if (isRec(result) && typeof (result as Rec).then === 'function') {
    return (result as unknown as Promise<unknown>).then(
      (value) => {
        observed(value)
        return value
      },
      (err: unknown) => {
        if (keepDocuments) noteAuthFailureFrom(err, 'read')
        throw err
      },
    )
  }
  return result
}

/** The document ids a `getDocument(id)` / `getDocuments([ids])` call asked for. */
function requestedIdsFrom(args: unknown[]): string[] {
  const first = args[0]
  if (typeof first === 'string') return [first]
  if (Array.isArray(first)) return first.filter((id): id is string => typeof id === 'string')
  return []
}

/* ------------------------------------------------------------ listen merge */

const PAIR_QUERY_RE = /^\*\[\s*_id\s+in\s+\$ids\s*\]$/

function isPairQuery(query: unknown): boolean {
  return typeof query === 'string' && PAIR_QUERY_RE.test(query.trim())
}

function idsFromParams(params: unknown): string[] {
  if (!isRec(params) || !Array.isArray(params.ids)) return []
  return params.ids.filter((id): id is string => typeof id === 'string')
}

function wrapListen(realListen: (...args: unknown[]) => unknown, self: object) {
  return (...args: unknown[]): unknown => {
    const upstream = realListen.apply(self, args)
    captureObservableCtor(upstream)

    const [query, params, options] = args
    const ids = idsFromParams(params)
    const pair = isPairQuery(query) && ids.length > 0
    const log = echoLog()
    if (log) {
      pushCapped(log.listens, {
        at: now(),
        query: typeof query === 'string' ? query.slice(0, 120) : String(query),
        ids: ids.length ? ids : undefined,
        pair,
        tag: isRec(options) && typeof options.tag === 'string' ? options.tag : undefined,
      })
    }

    // Non-pair listens (global preview `*`, search, releases, observe-document-set)
    // pass straight through. Injecting there would throw in applyMutationEvent,
    // which requires mendoza `effects` we do not produce.
    if (!pair || !isRec(upstream) || typeof (upstream as Rec).subscribe !== 'function') {
      return upstream
    }

    const upstream$ = upstream as unknown as MinimalObservable<unknown>
    // Learn the real revision chain from any upstream mutation event too, so a
    // change made by another client keeps our chain honest.
    const tapped$ = makeObservable<unknown>((subscriber) =>
      upstream$.subscribe({
        next: (event) => {
          protocol.observeUpstreamEvent(event)
          subscriber.next(event)
        },
        error: (err) => {
          /* A 401/403 on the pair stream is the session expiring mid-edit. Note
           * it — the same token is what a write would use — and then forward it
           * unchanged: this is a tap, not a filter, and Studio's own listener
           * error handling must still run. */
          noteAuthFailureFrom(err, 'listener')
          subscriber.error(err)
        },
        complete: () => subscriber.complete(),
      }),
    )

    return mergeObservables<unknown>([
      tapped$,
      localEvents(ids) as unknown as MinimalObservable<unknown>,
    ])
  }
}

/* --------------------------------------------------------- fluent blockers */

const fluentCache = new WeakMap<object, object>()

/**
 * Is this the sort of object `blockFluentCommit` must own?
 *
 * `commit` + `serialize` is the shape of both `Patch`/`ObservablePatch`
 * (`data/patch.ts`) and `Transaction`/`ObservableTransaction`
 * (`data/transaction.ts`), and neither class is exported from `@sanity/client`,
 * so a structural test is the only one available. It is checked on every value a
 * wrapped builder method returns — which is what closes Spike F gaps 18/19.
 */
function isFluentBuilder(value: unknown): value is object {
  return (
    isRec(value) && typeof value.commit === 'function' && typeof value.serialize === 'function'
  )
}

/**
 * The mutations a builder is about to commit.
 *
 * `Patch.serialize()` returns one `PatchMutationOperation` (`{id, set, …}`);
 * `Transaction.serialize()` returns the whole `Mutation[]`. Reading them is what
 * turns "the commit was blocked" into "the edit happened locally" — a commit the
 * facade catches but cannot echo still loses the user's work, which is the
 * failure mode this whole exercise is about.
 */
function serializeBuilder(target: object, label: string): Rec[] {
  const serialize = (target as Rec).serialize
  if (typeof serialize !== 'function') return []
  try {
    const value = (serialize as () => unknown).call(target)
    /* A Transaction serialises to the mutation array itself; a Patch serialises
     * to the bare patch operation, which is one mutation once it is named. The
     * shape of the return value is the discriminator — no need to know which
     * builder produced it. */
    if (Array.isArray(value)) return value.filter(isRec)
    return isRec(value) ? [{patch: value}] : []
  } catch (error) {
    noteError(`${label}.serialize() failed: ${String(error)}`)
    return []
  }
}

/** A `Transaction`'s own id, if it was given one (`BaseTransaction.transactionId`). */
function builderTransactionId(target: object): string | undefined {
  const read = (target as Rec).transactionId
  if (typeof read !== 'function') return undefined
  try {
    const value = (read as () => unknown).call(target)
    return typeof value === 'string' && value.length > 0 ? value : undefined
  } catch {
    return undefined
  }
}

/**
 * Turn any builder in a `client.mutate()` argument into the mutations it stands
 * for, so the planner can see the edit.
 *
 * `client.mutate(client.patch(id).set(…))` is documented `@sanity/client` usage
 * and `_mutate` serialises the builder on the way out (`data/dataMethods.ts`).
 * The facade already intercepted `mutate`, so nothing escaped — but the planner
 * only understands plain `{patch|create|delete: …}` mutations, so a builder
 * argument produced an EMPTY plan: blocked, acknowledged, never echoed, edit
 * gone. Same failure as gaps 18/19, reached from the other end of the builder.
 */
function normalizeBuilderArg(method: string, arg: unknown): unknown {
  if (method !== 'mutate') return arg
  const expand = (value: unknown): unknown[] =>
    isFluentBuilder(value) ? serializeBuilder(value, 'mutate') : [value]
  if (Array.isArray(arg)) return arg.flatMap(expand)
  return isFluentBuilder(arg) ? expand(arg) : arg
}

/**
 * `client.patch(id)` / `client.transaction()` return builders bound to the REAL
 * client, so their `commit()` would bypass the facade entirely. Wrap them and
 * re-wrap every builder they hand back so the chain can never escape.
 *
 * GATE E, gaps 18/19. This used to re-wrap only `result === t` — the fluent
 * `this` returns. `clone()` returns a **new** builder still bound to the real
 * client (`patch.ts:284`, `transaction.ts:148`), so `patch(id).clone().commit()`
 * walked straight out of the facade and the edit never reached local echo.
 * Every builder-shaped return is now re-wrapped, which covers `clone()`,
 * `clone().clone()`, chains taken off a clone, and any future copy method.
 */
function blockFluentCommit<T extends object>(target: T, label: string, kind: Kind): T {
  const cached = fluentCache.get(target)
  if (cached) return cached as T
  const methods = new Map<PropertyKey, unknown>()
  const proxy = new Proxy(target, {
    get(t, prop) {
      const value = Reflect.get(t, prop)
      if (typeof value !== 'function') return value
      const existing = methods.get(prop)
      if (existing) return existing
      const name = String(prop)
      const wrapped = (...args: unknown[]): unknown => {
        if (name === 'commit') {
          const mutations = serializeBuilder(t, label)
          const transactionId =
            transactionIdFromOptions(args[0]) ?? builderTransactionId(t) ?? nextTransactionId()
          const plan = protocol.planMutations(mutations)
          const entry = recordBlocked(
            `${label}.commit`,
            mutations,
            transactionId,
            plan.plans.length > 0,
          )
          if (plan.plans.length === 0) {
            noteError(`${label}.commit blocked without echo (nothing serialisable to echo)`)
          }
          return blockedResult(
            kind,
            syntheticResult(transactionId, true),
            () => scheduleEcho(plan.plans, transactionId),
            () => persistPlan(plan, transactionId),
            entry,
          )
        }
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
        const result = (value as any).apply(t, args)
        if (result === t) return proxy
        /* `clone()` and friends: a new builder, same real client. Wrap it or the
         * next `commit()` is outside the facade. */
        return isFluentBuilder(result) ? blockFluentCommit(result as object, label, kind) : result
      }
      methods.set(prop, wrapped)
      return wrapped
    },
  }) as T
  fluentCache.set(target, proxy)
  return proxy
}

/* ------------------------------------------------- un-echoable write refusal */

/**
 * Answer a write the overlay cannot represent with an error instead of a lie.
 *
 * Asset uploads, Agent Actions and dataset administration have no overlay
 * spelling: there is nothing to echo and nothing to persist. The previous
 * behaviour was worse than either option here — the call was not intercepted at
 * all, so it reached the network, moved staging, and left the overlay behind
 * (or, with the proxy in front, died on an opaque 403 halfway through an edit).
 *
 * A synthetic success would be worse still: `assets.upload` resolving to
 * `{transactionId}` hands Studio a value shaped nothing like the asset document
 * it awaits. An error is the one answer that is true, and it names the layer
 * that produced it so the failure is not mistaken for a Content Lake outage.
 */
function refuseUnechoable(kind: Kind, label: string, arg: unknown, reason: string): unknown {
  const entry = recordBlocked(label, arg, undefined, false)
  if (entry) entry.handled = false
  const error = new Error(
    `[spike-a] local echo blocked ${label}: ${reason}. The overlay cannot represent this ` +
      'write, so letting it through would put the editor and the overlay out of sync.',
  )
  noteError(error.message)
  console.error(error.message)
  return kind === 'observable' ? observableThrowing<Rec>(error) : Promise.reject(error)
}

const UNECHOABLE_REASON: Record<string, string> = {
  asset: 'asset uploads are binary and live outside the document overlay',
  'agent-action': 'Agent Actions mutate documents server-side, where the overlay cannot follow',
  'dataset-admin': 'dataset administration is a project-plane operation, not a document edit',
}

/* --------------------------------------------------------- the identity tap */

/**
 * Watch an identity probe go by and, if it proves a live credential, bring the
 * session back.
 *
 * GATE E follow-up: `restoreSession()` existed and was tested, but nothing ever
 * called it — a session that 401'd stayed write-refusing until a full reload.
 * Fail-closed and deliberate, but a real limitation, and one the user cannot do
 * anything about from inside the editor.
 *
 * The signal is Studio's own: after a 401 Studio calls `refreshWorkbenchToken()`
 * and the reissued token arrives on the `auth.token` subscription, which drives
 * `probeAuthState` → `GET /users/me` (or `probeCurrentUser` → `GET /auth/id`).
 * So the facade piggybacks on a round trip that already happens at exactly the
 * right moment, and adds no polling of its own.
 *
 * It is a TAP: the response is forwarded untouched, errors included.
 */
function tapIdentityProbe(result: unknown, label: string): unknown {
  const observed = (value: unknown): void => {
    if (identityProofFrom(value) === undefined) return
    if (protocol.sessionState() !== 'unauthenticated') return
    protocol.restoreSession()
    syncSessionLog(true)
    const message =
      `[spike-a] ${label} returned a live identity — the session is authenticated again ` +
      'and writes resume'
    noteError(message)
    console.info(message)
  }

  if (isRec(result) && typeof (result as Rec).subscribe === 'function') {
    captureObservableCtor(result)
    const source = result as unknown as MinimalObservable<unknown>
    return makeObservable<unknown>((subscriber) =>
      source.subscribe({
        next: (value) => {
          observed(value)
          subscriber.next(value)
        },
        error: (err) => subscriber.error(err),
        complete: () => subscriber.complete(),
      }),
    )
  }
  if (isRec(result) && typeof (result as Rec).then === 'function') {
    return (result as unknown as Promise<unknown>).then((value) => {
      observed(value)
      return value
    })
  }
  observed(result)
  return result
}

/* -------------------------------------------------------- namespace proxies */

/**
 * The object-valued namespaces a `SanityClient` hangs off itself
 * (`SanityClient.ts:1189-1200`), and the ones nested inside them.
 *
 * Until Gate E the echo proxy descended into `observable` and nothing else, so
 * `client.assets`, `client.agent.action`, `client.datasets` and
 * `client.releases` were returned untouched — Spike F gaps 21/22, 23 and 24.
 * They do not route through `client.request` either: every namespace client
 * holds its own `#httpRequest` and calls it directly, so guarding `request` was
 * never going to reach them.
 */
const NAMESPACE_ROOTS = new Set([
  'assets',
  'datasets',
  'projects',
  'users',
  'releases',
  'live',
  'agent',
  'mediaLibrary',
])

/** namespace path -> the property under it that is itself a namespace. */
const NESTED_NAMESPACES: Record<string, string> = {agent: 'action', mediaLibrary: 'video'}

const namespaceCache = new WeakMap<object, object>()
const namespaceMethods = new WeakMap<object, Map<PropertyKey, unknown>>()

/**
 * Identity-stable, exactly like {@link echoProxy}: one proxy per namespace
 * object, one wrapper per method. Studio reads `client.live` inside a React
 * effect dependency array on every render (`LiveQueries-rJao7vYj.js:36-45`), so
 * a fresh proxy per access is the ~40 000-call resubscribe storm again — pinned
 * at 20 000 renders in `test/spike-a-client-identity.test.ts`.
 */
function echoNamespace<T extends object>(target: T, path: string, kind: Kind): T {
  const cached = namespaceCache.get(target)
  if (cached) return cached as T

  const proxy = new Proxy(target, {
    get(t, prop) {
      const value = Reflect.get(t, prop)
      const name = String(prop)

      if (NESTED_NAMESPACES[path] === name && isRec(value)) {
        return echoNamespace(value as object, `${path}.${name}`, kind)
      }
      if (typeof value !== 'function') return value

      let perTarget = namespaceMethods.get(t)
      if (!perTarget) {
        perTarget = new Map()
        namespaceMethods.set(t, perTarget)
      }
      const existing = perTarget.get(prop)
      if (existing) return existing

      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      const fn = value as (...args: any[]) => unknown
      const label = `${path}.${name}`
      let wrapped: (...args: unknown[]) => unknown

      if (namespaceMethodKind(path, name) === 'write') {
        wrapped = (...args: unknown[]): unknown =>
          refuseUnechoable(kind, label, args[0], namespaceRefusalReason(path))
      } else if (path === 'users' && name === 'getById') {
        /* `client.users.getById('me')` is the same credential proof as
         * `request({uri: '/users/me'})` — it builds that exact URL — so the
         * refresh signal must not depend on which spelling the caller picked. */
        wrapped = (...args: unknown[]): unknown =>
          args[0] === 'me' ? tapIdentityProbe(fn.apply(t, args), label) : fn.apply(t, args)
      } else {
        wrapped = (...args: unknown[]): unknown => fn.apply(t, args)
      }

      perTarget.set(prop, wrapped)
      return wrapped
    },
  }) as T

  namespaceCache.set(target, proxy)
  return proxy
}

function namespaceRefusalReason(path: string): string {
  if (path === 'assets') return UNECHOABLE_REASON.asset as string
  if (path === 'agent.action') return UNECHOABLE_REASON['agent-action'] as string
  if (path === 'datasets') return UNECHOABLE_REASON['dataset-admin'] as string
  if (path === 'releases') {
    return 'release administration is not a document edit the overlay can represent'
  }
  return 'this namespace method is not one the overlay knows how to echo'
}

/* ---------------------------------------------------------- the echo proxy */

const echoCache = new WeakMap<object, object>()
const echoMethods = new WeakMap<object, Map<PropertyKey, unknown>>()

function echoProxy<T extends object>(target: T, kind: Kind): T {
  const cached = echoCache.get(target)
  if (cached) return cached as T

  const proxy = new Proxy(target, {
    get(t, prop) {
      // NOTE: receiver intentionally defaults to `t`. Forwarding the outer
      // (instrumented) proxy as receiver would break any @sanity/client getter
      // that reads a private class field.
      const value = Reflect.get(t, prop)
      const name = String(prop)

      if (name === 'observable' && isRec(value)) {
        return echoProxy(value as object, 'observable')
      }
      if (NAMESPACE_ROOTS.has(name) && isRec(value)) {
        return echoNamespace(value as object, name, kind)
      }
      if (typeof value !== 'function') return value

      let perTarget = echoMethods.get(t)
      if (!perTarget) {
        perTarget = new Map()
        echoMethods.set(t, perTarget)
      }
      const existing = perTarget.get(prop)
      if (existing) return existing

      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      const fn = value as (...args: any[]) => unknown
      let wrapped: (...args: unknown[]) => unknown

      if (name === 'listen') {
        wrapped = wrapListen(fn as (...args: unknown[]) => unknown, t)
      } else if (name === 'action') {
        wrapped = (...args: unknown[]): unknown => {
          const transactionId = transactionIdFromOptions(args[1]) ?? nextTransactionId()
          const plan = protocol.planActions(args[0])
          const entry = recordBlocked('action', args[0], transactionId, plan.plans.length > 0)
          if (plan.unsupported.length > 0) {
            noteError(`action blocked without echo for: ${plan.unsupported.join(', ')}`)
          }
          return blockedResult(
            kind,
            syntheticResult(transactionId, false),
            () => scheduleEcho(plan.plans, transactionId),
            () => persistPlan(plan, transactionId),
            entry,
          )
        }
      } else if (name === 'dataRequest') {
        wrapped = (...args: unknown[]): unknown => {
          const endpoint = typeof args[0] === 'string' ? args[0] : ''
          if (!MUTATING_DATA_ENDPOINTS.has(endpoint)) return fn.apply(t, args)
          const body = args[1]
          const transactionId =
            (isRec(body) && typeof body.transactionId === 'string' ? body.transactionId : undefined) ??
            transactionIdFromOptions(args[2]) ??
            nextTransactionId()
          const isMutate = endpoint === 'mutate'
          const plan = isMutate
            ? protocol.planMutations(body)
            : protocol.planActions(isRec(body) ? body.actions : undefined)
          const entry = recordBlocked(
            `dataRequest:${endpoint}`,
            body,
            transactionId,
            plan.plans.length > 0,
          )
          return blockedResult(
            kind,
            syntheticResult(transactionId, isMutate),
            () => scheduleEcho(plan.plans, transactionId),
            () => persistPlan(plan, transactionId),
            entry,
          )
        }
      } else if (name === 'request') {
        wrapped = (...args: unknown[]): unknown => {
          const options = args[0]
          const url = isRec(options) ? (options.url ?? options.uri) : undefined
          const method = isRec(options) ? String(options.method ?? 'GET').toUpperCase() : 'GET'

          /* Studio's logout is `client.request({uri: '/auth/logout', method:
           * 'POST'})` on a middleware-stripped clone — sanity 6.8.0,
           * `WorkspaceLoader-BRx2afZV.js` `logout()`. It is passed straight
           * through (swallowing it would leave a live token behind) but the
           * session ends here, synchronously: `Promise.allSettled` means Studio
           * does not wait for the response, and neither may the pane release. */
          if (isLogoutEndpoint(url)) {
            protocol.logout()
            const log = echoLog()
            if (log) Object.assign(log.revs, protocol.revisions())
            syncSessionLog()
            return fn.apply(t, args)
          }

          /* The token-refresh signal (Gate E follow-up). Forwarded untouched;
           * see `tapIdentityProbe` for why a bare 200 is not enough. */
          if (isIdentityProbeEndpoint(url)) {
            return tapIdentityProbe(fn.apply(t, args), `request(${String(url)})`)
          }

          const plane = classifyWriteEndpoint(url)
          const isWrite = plane !== undefined && method !== 'GET' && method !== 'HEAD'
          if (!isWrite) return fn.apply(t, args)
          /* Asset / Agent Action / dataset-admin URLs reach the network through
           * `request` too (gaps 21/23/24 and gap 7's non-`/data/` spellings) and
           * there is nothing to echo for any of them. */
          if (plane !== 'documents') {
            return refuseUnechoable(
              kind,
              `request(${String(url)})`,
              options,
              UNECHOABLE_REASON[plane] as string,
            )
          }
          const body = isRec(options) ? options.body : undefined
          const transactionId =
            (isRec(body) && typeof body.transactionId === 'string' ? body.transactionId : undefined) ??
            nextTransactionId()
          const plan = protocol.planMutations(body)
          const entry = recordBlocked('request', options, transactionId, plan.plans.length > 0)
          return blockedResult(
            kind,
            syntheticResult(transactionId, true),
            () => scheduleEcho(plan.plans, transactionId),
            () => persistPlan(plan, transactionId),
            entry,
          )
        }
      } else if (WRITE_METHODS.has(name)) {
        wrapped = (...args: unknown[]): unknown => {
          const transactionId =
            transactionIdFromOptions(args[1]) ?? transactionIdFromOptions(args[2]) ?? nextTransactionId()
          /* `args[1]` carries the `tag`, which is the only trace of §18.9
           * duplicate on the wire: Studio's duplicate is
           * `client.create(copy, {tag: 'document.duplicate'})`, not an action. */
          const plan = protocol.planWrite(name, normalizeBuilderArg(name, args[0]), args[1])
          const entry = recordBlocked(name, args[0], transactionId, plan.plans.length > 0)
          return blockedResult(
            kind,
            syntheticResult(transactionId, true),
            () => scheduleEcho(plan.plans, transactionId),
            () => persistPlan(plan, transactionId),
            entry,
          )
        }
      } else if (name === 'patch' || name === 'transaction') {
        wrapped = (...args: unknown[]): unknown => {
          const result = fn.apply(t, args)
          return isRec(result) ? blockFluentCommit(result as object, name, kind) : result
        }
      } else if (name === 'withConfig' || name === 'clone' || name === 'withUrlSourceMapping') {
        // CRITICAL: Studio reaches the Actions API through
        // `client.withConfig({apiVersion:'2025-02-19'}).observable.action(...)`.
        // If withConfig returned a bare client the write would escape the facade.
        wrapped = (...args: unknown[]): unknown => {
          const result = fn.apply(t, args)
          return isRec(result) ? echoProxy(result as object, kind) : result
        }
      } else if (READ_TAP_METHODS.has(name)) {
        /* No longer a tap: `getDocument` / `getDocuments` answer with the virtual
         * document. Revision seeding and the hydration replay still run first,
         * on the unsubstituted upstream value. */
        wrapped = (...args: unknown[]): unknown =>
          overlayVersionRead(fn.apply(t, args), requestedIdsFrom(args))
      } else if (name === 'fetch') {
        wrapped = (...args: unknown[]): unknown =>
          overlayFetch(kind, fn as (...a: unknown[]) => unknown, t, args)
      } else {
        wrapped = (...args: unknown[]): unknown => fn.apply(t, args)
      }

      perTarget.set(prop, wrapped)
      return wrapped
    },
  }) as T

  echoCache.set(target, proxy)
  return proxy
}

/* -------------------------------------------------------------- public API */

/**
 * Wrap a real SanityClient so every write is blocked, recorded, answered with a
 * synthetic `{transactionId}` and echoed back to Studio's document pair listener.
 * Identity-stable: same input client -> same proxy, same method -> same function.
 */
export function wrapWithLocalEcho(client: SanityClient): SanityClient {
  const log = echoLog()
  if (log) {
    log.enabled = true
    log.persist.enabled = isPersistEnabled()
    log.persist.url = overlayUrl()
    log.reads.strict = isStrictQueriesEnabled()
  }
  probeObservableCtor(client as unknown as Rec)
  /* Start the overlay read before Studio opens a pane: the replay is gated on
   * this promise, so hydrating early only shortens the window in which a pane
   * could render pre-overlay content. */
  if (isPersistEnabled()) void hydrationReady()
  return echoProxy(client as unknown as object, 'promise') as unknown as SanityClient
}
