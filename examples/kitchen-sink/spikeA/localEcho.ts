// SPIKE A — Track A: "local echo" write-block facade (PRD §36.1, §21.4.1).
//
// WHAT THIS DOES
// When `localStorage.SPIKE_LOCAL_ECHO === '1'` every write leaving the Studio
// client is intercepted, recorded to `window.__SPIKE_ECHO__`, answered with a
// synthetic `{transactionId}` success, and echoed back to the Studio's document
// pair listener as a synthetic `mutation` event. No write reaches the network.
// This is the minimal proof that an overlay can own the write path and settle
// Studio's save state without a server.
//
// WHY IT IS SHAPED THIS WAY (evidence gathered from sanity 6.8.0 sources —
// keep these notes, they are the load-bearing findings):
//
//  1. Studio commits edits via `client.observable.action(actions, {tag:
//     'document.commit', transactionId})`. The transactionId is generated by
//     Studio's @sanity/mutator BufferedDocument and passed IN. The echoed
//     listener event MUST reuse it, otherwise `BufferedDocument.consumeUnresolved`
//     never matches the submitted mutation and the pane stays "unsaved" forever.
//     (sanity/lib/datastores-*.js `commitActions`)
//
//  2. `getPairListener` pipes the listen stream through
//     `sequentializeListenerEvents()`, which seeds its base revision from the
//     *snapshot* fetched via `client.observable.getDocuments([published, draft])`
//     and then requires an unbroken `previousRev -> resultRev` chain. A made-up
//     base rev (e.g. 'local-echo-base') is therefore NOT viable: it never chains,
//     the events sit in the buffer and after 30s the stream throws
//     DeadlineExceededError. So we tap `getDocument(s)`/`fetch` results to learn
//     the REAL `_rev` and chain from it. (`sequentializeListenerEvents`)
//
//  3. `@sanity/mutator` `Mutation.apply()` really applies `event.mutations` to
//     HEAD and sets `_rev = resultRev || transactionId`, and throws if
//     `previousRev !== doc._rev`. So the mutations array must contain the actual
//     patch (not just the guard patch) or HEAD silently diverges from the
//     optimistic local document.
//
//  4. If the draft does not exist yet, `Document.considerIncoming` only accepts
//     a mutation whose FIRST entry is a create/createIfNotExists/createOrReplace.
//     The Actions API edit semantics are "create the draft from the current
//     published version, then patch", so we synthesise exactly that using the
//     published document captured from the pair snapshot fetch.
//
//  5. `effects` (mendoza) is deliberately omitted. It is only consumed by
//     `createObserveDocument` / `applyMutationEventEffects`, which is fed by the
//     GLOBAL preview listener (`*`), not by the pair listener. That is also why
//     we must NOT inject synthetic events into non-pair listens: that code path
//     throws "Mutation event is missing effects" when effects are absent.
//     => If document panes fail to converge (title/preview stale, or a thrown
//     "missing effects"), the next step is to compute a real mendoza diff and
//     attach `effects: {apply, revert}`.
//
//  6. Identity stability is mandatory (see instrumentedClient.ts): every wrapper
//     here is memoized per target+property. A fresh function per property access
//     puts Studio into an infinite resubscribe loop.
//
// NOTE: this file intentionally does not `import 'rxjs'` — rxjs is not a direct
// dependency of the example app and pnpm's strict node_modules layout makes it
// unresolvable from here (installs are out of scope for the spike). Instead we
// capture the real rxjs `Observable` constructor off an observable produced by
// the real client, so every synthetic stream we hand back to Studio is a
// genuine rxjs Observable with working `pipe`/`lift`/interop.
import type {SanityClient} from '@sanity/client'

